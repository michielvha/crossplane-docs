func formatHTML(doc Document, c Config) ([]byte, error) {
	sections := make([]string, 0, len(c.Sections))
	for _, section := range c.Sections {
		if !slices.Contains(sections, section) {
			sections = append(sections, section)
		}
	}
	c.Sections = sections
	w := &writer{config: c}
	fmt.Fprintf(&w.buf, `<!doctype html>
<html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1"><meta name="theme-color" content="#f5f8f8" media="(prefers-color-scheme: light)"><meta name="theme-color" content="#020814" media="(prefers-color-scheme: dark)"><link rel="icon" href="data:,"><title>%s</title><script type="text/javascript">%s</script><style>%s%s</style></head><body data-html-layout="%s"><a class="skip" href="#content">Skip to reference</a><header class="appbar"><span class="brand">crossplane<span>docs</span></span><span class="document-title">%s</span>%s</header><div class="shell"><nav class="rail" aria-label="Contents">`, html.EscapeString(doc.Title), htmlThemeInit, htmlStyle, c.Settings.Style, c.HTMLLayout, html.EscapeString(doc.Title), htmlThemeButton)
	for _, section := range c.Sections {
		label := map[string]string{"apis": "API reference", "compositions": "Compositions", "scenarios": "Rendered scenarios", "examples": "Examples"}[section]
		fmt.Fprintf(&w.buf, `<a href="#%s">%s</a>`, section, label)
		if section == "apis" {
			for i, api := range doc.APIs {
				fmt.Fprintf(&w.buf, `<a class="api-nav" href="#api-%d">%s <small>%s / %s</small></a>`, i, html.EscapeString(api.Kind), html.EscapeString(api.Group), html.EscapeString(api.Version))
			}
		}
	}
	w.buf.WriteString(`</nav><main id="content">`)
	if c.HeaderFrom != "" {
		content, err := os.ReadFile(c.HeaderFrom)
		if err != nil {
			return nil, err
		}
		w.buf.Write(content)
	}
	if !slices.Contains(c.Sections, "apis") {
		fmt.Fprintf(&w.buf, `<h1>%s</h1>`, html.EscapeString(doc.Title))
	}
	for _, section := range c.Sections {
		if section == "apis" {
			writeHTMLAPIs(w, doc, c)
			continue
		}
		if section == "examples" && c.HTMLLayout == "reference" && slices.Contains(c.Sections, "apis") {
			writeHTMLExampleInventory(w, doc)
			continue
		}
		one := c
		one.Sections = []string{section}
		writeSections(w, doc, one)
	}
	if c.FooterFrom != "" {
		content, err := os.ReadFile(c.FooterFrom)
		if err != nil {
			return nil, err
		}
		w.buf.Write(content)
	}
	fmt.Fprintf(&w.buf, `<footer>Generated by crossplane-docs. Documentation model %s.</footer></main></div><script type="module">%s</script></body></html>`, html.EscapeString(doc.SchemaVersion), htmlScript)
	return append(w.buf.Bytes(), '\n'), nil
}

func writeHTMLAPIs(w *writer, doc Document, c Config) {
	w.buf.WriteString(`<section id="apis" aria-label="API reference">`)
	// Controls are revealed only after enhancement, so the plain file has no dead UI.
	w.buf.WriteString(`<div class="controls" hidden><div class="control"><label for="api-select">API resource</label><select id="api-select" name="resource">`)
	groups := map[string]string{}
	var resources []string
	for _, api := range doc.APIs {
		key := api.Group + "/" + api.Kind
		if _, ok := groups[key]; ok {
			continue
		}
		id := fmt.Sprintf("resource-%d", len(resources))
		groups[key] = id
		resources = append(resources, key)
		fmt.Fprintf(&w.buf, `<option value="%s">%s / %s</option>`, id, html.EscapeString(api.Kind), html.EscapeString(api.Group))
	}
	w.buf.WriteString(`</select></div><div class="control"><label for="version-select">API version</label><select id="version-select" name="version">`)
	for i, api := range doc.APIs {
		fmt.Fprintf(&w.buf, `<option value="api-%d" data-resource="%s">%s</option>`, i, groups[api.Group+"/"+api.Kind], html.EscapeString(api.Version))
	}
	w.buf.WriteString(`</select></div><div class="control"><label for="requirement-filter">Field requirement</label><select id="requirement-filter" name="requirement"><option value="all">All fields</option><option value="required">Required</option><option value="optional">Optional</option></select></div><div class="control search-control"><label for="field-search">Find a field</label><input type="search" id="field-search" name="query" autocomplete="off" spellcheck="false" placeholder="region, networks…"></div></div><p id="search-status" role="status" aria-live="polite"></p>`)
	for i, api := range doc.APIs {
		id := fmt.Sprintf("api-%d", i)
		fields := append([]Field(nil), api.Fields...)
		// Cross-field validation belongs after the property reference, not before it.
		sort.SliceStable(fields, func(i, j int) bool { return fields[i].Path != "spec" && fields[j].Path == "spec" })
		fmt.Fprintf(&w.buf, `<section class="api-panel" id="%s" data-resource="%s" data-version="%s" data-preferred="%t"><header class="api-header"><div class="identity"><code>%s/%s</code><span class="pill">%s</span></div><h1>%s</h1>`, id, groups[api.Group+"/"+api.Kind], html.EscapeString(api.Version), api.Referenceable, html.EscapeString(api.Group), html.EscapeString(api.Version), html.EscapeString(api.Scope), html.EscapeString(api.Kind))
		if c.Settings.Descriptions {
			w.para(api.Description)
		}
		fmt.Fprintf(&w.buf, `<dl class="api-facts"><div><dt>Served</dt><dd>%t</dd></div><div><dt>Referenceable</dt><dd>%t</dd></div>`, api.Served, api.Referenceable)
		if api.ClaimKind != "" {
			fmt.Fprintf(&w.buf, `<div><dt>Claim kind</dt><dd><code>%s</code></dd></div>`, html.EscapeString(api.ClaimKind))
		}
		w.buf.WriteString(`</dl></header>`)
		var examples []int
		if c.Settings.Examples && slices.Contains(c.Sections, "examples") {
			for index, example := range doc.Examples {
				if htmlExampleMatches(example, api) {
					examples = append(examples, index)
				}
			}
		}
		if c.HTMLLayout == "reference" && len(examples) > 0 {
			w.buf.WriteString(`<div class="mobile-views" hidden><button type="button" data-view="fields" aria-pressed="true">Fields</button><button type="button" data-view="example" aria-pressed="false">Example YAML</button></div>`)
		}
		if c.HTMLLayout == "explorer" {
			fmt.Fprintf(&w.buf, `<button type="button" class="browse-fields" data-browse-fields aria-expanded="false" aria-controls="%s-browser" hidden>Browse fields</button>`, id)
		}
		w.buf.WriteString(`<p class="empty-fields" role="status" hidden>No matching fields. Try another field name or change the requirement filter.</p>`)
		w.buf.WriteString(`<div class="schema-layout">`)
		if c.HTMLLayout == "explorer" {
			fmt.Fprintf(&w.buf, `<nav class="field-browser" id="%s-browser" aria-label="Schema fields">`, id)
			for j, field := range fields {
				fmt.Fprintf(&w.buf, `<a class="field-link" href="#%s-field-%d" data-path="%s"><code>%s</code></a>`, id, j, html.EscapeString(field.Path), html.EscapeString(field.Path))
			}
			w.buf.WriteString(`</nav>`)
		}
		w.buf.WriteString(`<div class="field-list"><h2>Field reference</h2><p class="field-help">Required markers apply within each field’s parent object.</p>`)
		if c.HTMLLayout == "compact" {
			w.buf.WriteString(`<div class="table-wrap field-table"><table role="table"><thead role="rowgroup"><tr role="row">`)
			for _, column := range c.Columns {
				fmt.Fprintf(&w.buf, `<th scope="col" role="columnheader">%s</th>`, html.EscapeString(column))
			}
			w.buf.WriteString(`</tr></thead><tbody role="rowgroup">`)
		}
		if c.HTMLLayout == "reference" {
			writeHTMLFieldGroups(w, fields, id, c)
		} else {
			for j, field := range fields {
				writeHTMLField(w, field, fmt.Sprintf("%s-field-%d", id, j), c)
			}
		}
		if c.HTMLLayout == "compact" {
			w.buf.WriteString(`</tbody></table></div>`)
		}
		w.buf.WriteString(`</div>`)
		if c.HTMLLayout == "reference" && len(examples) > 0 {
			w.buf.WriteString(`<aside class="paired-example" aria-label="Example manifest"><h2>Example manifest</h2>`)
			for _, index := range examples {
				example := doc.Examples[index]
				fmt.Fprintf(&w.buf, `<section class="example-manifest" id="api-%d-example-%d" tabindex="-1" aria-label="Example manifest: %s">`, i, index, html.EscapeString(htmlExampleLabel(example, index)))
				w.code("yaml", yamlText(example))
				w.buf.WriteString(`</section>`)
			}
			w.buf.WriteString(`</aside>`)
		}
		w.buf.WriteString(`</div>`)
		if len(api.Constraints) > 0 {
			w.heading(2, "API validation")
			writeHTMLConstraints(w, api.Constraints)
		}
		if len(api.PrinterColumns) > 0 {
			w.heading(2, "Printer columns")
			w.code("yaml", yamlText(api.PrinterColumns))
		}
		w.buf.WriteString(`</section>`)
	}
	w.buf.WriteString(`</section>`)
}

func writeHTMLFieldGroups(w *writer, fields []Field, apiID string, c Config) {
	groups := map[string][]int{}
	var order []string
	for i, field := range fields {
		parts := strings.Split(field.Path, ".")
		key := parts[0]
		if key == "spec" && len(parts) > 1 {
			key += "." + strings.TrimSuffix(parts[1], "[]")
		}
		if _, exists := groups[key]; !exists {
			order = append(order, key)
		}
		groups[key] = append(groups[key], i)
	}
	opened := false
	for _, key := range order {
		indices := groups[key]
		grouped := len(indices) > 1 || key == "spec"
		if grouped {
			open := ""
			if !opened {
				open = " open"
				opened = true
			}
			label := key
			if key == "spec" {
				label = "Cross-field validation"
				for _, index := range indices {
					field := fields[index]
					if field.Description != "" || field.HasDefault || field.Nullable || field.Required {
						label = "Spec object"
					}
				}
			}
			fmt.Fprintf(&w.buf, `<details class="field-group"%s><summary><code>%s</code></summary>`, open, html.EscapeString(label))
		}
		for _, index := range indices {
			writeHTMLField(w, fields[index], fmt.Sprintf("%s-field-%d", apiID, index), c)
		}
		if grouped {
			w.buf.WriteString(`</details>`)
		}
	}
}

func htmlExampleMatches(example Object, api API) bool {
	return text(example, "apiVersion") == api.Group+"/"+api.Version && (text(example, "kind") == api.Kind || text(example, "kind") == api.ClaimKind)
}

func htmlExampleLabel(example Object, index int) string {
	name := text(example, "metadata", "name")
	if name == "" {
		name = text(example, "metadata", "generateName")
	}
	if name == "" {
		name = fmt.Sprintf("Example %d", index+1)
	}
	if namespace := text(example, "metadata", "namespace"); namespace != "" {
		name = namespace + "/" + name
	}
	return strings.TrimSpace(text(example, "kind") + " " + name)
}

func writeHTMLExampleInventory(w *writer, doc Document) {
	w.section("examples", "Example resources")
	w.buf.WriteString(`<ul class="example-index">`)
	for index, example := range doc.Examples {
		apiIndex := -1
		for i, api := range doc.APIs {
			if htmlExampleMatches(example, api) {
				apiIndex = i
				break
			}
		}
		w.buf.WriteString(`<li>`)
		if apiIndex >= 0 {
			fmt.Fprintf(&w.buf, `<a href="#api-%d-example-%d"><code>%s</code><span>%s</span></a>`, apiIndex, index, html.EscapeString(htmlExampleLabel(example, index)), html.EscapeString(text(example, "apiVersion")))
		} else {
			fmt.Fprintf(&w.buf, `<p>%s</p>`, html.EscapeString(htmlExampleLabel(example, index)))
			w.code("yaml", yamlText(example))
		}
		w.buf.WriteString(`</li>`)
	}
	w.buf.WriteString(`</ul>`)
}

func writeHTMLField(w *writer, field Field, id string, c Config) {
	search := field.Path
	if c.Settings.Descriptions {
		search += " " + field.Description
	}
	if c.HTMLLayout == "compact" {
		fmt.Fprintf(&w.buf, `<tr role="row" class="field-entry" id="%s" data-path="%s" data-required="%t" data-search="%s">`, id, html.EscapeString(field.Path), field.Required, html.EscapeString(strings.ToLower(search)))
		for _, column := range c.Columns {
			fmt.Fprintf(&w.buf, `<td role="cell" data-label="%s">`, html.EscapeString(column))
			writeHTMLFieldValue(w, field, column, c)
			w.buf.WriteString(`</td>`)
		}
		w.buf.WriteString(`</tr>`)
		return
	}
	fmt.Fprintf(&w.buf, `<article class="field-entry" id="%s" data-path="%s" data-required="%t" data-search="%s"><h3 tabindex="-1"><code>%s</code>`, id, html.EscapeString(field.Path), field.Required, html.EscapeString(strings.ToLower(search)), html.EscapeString(field.Path))
	if slices.Contains(c.Columns, "type") {
		fmt.Fprintf(&w.buf, `<span class="field-type">%s</span>`, html.EscapeString(field.Type))
	}
	if slices.Contains(c.Columns, "required") && field.Required {
		w.buf.WriteString(`<span class="required">required</span>`)
	}
	if c.Settings.Anchors {
		fmt.Fprintf(&w.buf, `<a class="permalink" href="#%s" aria-label="Link to %s">#</a>`, id, html.EscapeString(field.Path))
	}
	w.buf.WriteString(`</h3>`)
	if slices.Contains(c.Columns, "description") && c.Settings.Descriptions {
		w.para(field.Description)
	}
	w.buf.WriteString(`<dl class="field-facts">`)
	for _, column := range c.Columns {
		if column == "path" || column == "type" || column == "description" || column == "required" {
			continue
		}
		if column == "default" && !field.HasDefault {
			continue
		}
		if column == "constraints" && len(field.Constraints) == 0 && field.Reference == "" && !field.Nullable {
			continue
		}
		fmt.Fprintf(&w.buf, `<div><dt>%s</dt><dd>`, html.EscapeString(column))
		writeHTMLFieldValue(w, field, column, c)
		w.buf.WriteString(`</dd></div>`)
	}
	w.buf.WriteString(`</dl></article>`)
}

func writeHTMLFieldValue(w *writer, field Field, column string, c Config) {
	switch column {
	case "path":
		fmt.Fprintf(&w.buf, `<code>%s</code>`, html.EscapeString(field.Path))
	case "type":
		fmt.Fprintf(&w.buf, `<code>%s</code>`, html.EscapeString(field.Type))
		if field.Nullable {
			w.buf.WriteString(` <span class="muted">nullable</span>`)
		}
	case "description":
		if c.Settings.Descriptions {
			w.para(field.Description)
		}
	case "required":
		if field.Required {
			w.buf.WriteString(`<span class="required">required</span>`)
		} else {
			w.buf.WriteString(`<span class="muted">optional</span>`)
		}
	case "default":
		if field.HasDefault {
			value := compact(field.Default)
			if field.Default == nil {
				value = "null"
			} else if s, ok := field.Default.(string); ok {
				value = strconv.Quote(s)
			}
			fmt.Fprintf(&w.buf, `<code>%s</code>`, html.EscapeString(value))
		} else {
			w.buf.WriteString(`<span class="muted">None</span>`)
		}
	case "constraints":
		if field.Nullable {
			w.buf.WriteString(`<p>Nullable</p>`)
		}
		if field.Reference != "" {
			fmt.Fprintf(&w.buf, `<p>Reference <code>%s</code></p>`, html.EscapeString(field.Reference))
		}
		if len(field.Constraints) > 0 {
			writeHTMLConstraints(w, field.Constraints)
		}
	}
}

func writeHTMLConstraints(w *writer, constraints Object) {
	labels := map[string]string{"enum": "Allowed values", "minimum": "Minimum", "maximum": "Maximum", "minLength": "Min length", "maxLength": "Max length", "minItems": "Min items", "maxItems": "Max items", "pattern": "Pattern", "format": "Format", "x-kubernetes-list-type": "List behavior", "x-kubernetes-list-map-keys": "Identity keys", "x-kubernetes-map-type": "Map behavior", "x-kubernetes-validations": "CEL validation"}
	keys := make([]string, 0, len(constraints))
	for key := range constraints {
		keys = append(keys, key)
	}
	sort.Strings(keys)
	w.buf.WriteString(`<dl class="constraint-list">`)
	for _, key := range keys {
		label := labels[key]
		if label == "" {
			label = key
		}
		fmt.Fprintf(&w.buf, `<div><dt>%s</dt><dd>`, html.EscapeString(label))
		value := constraints[key]
		switch v := value.(type) {
		case []interface{}:
			structured := false
			for _, item := range v {
				if _, ok := item.(map[string]interface{}); ok {
					structured = true
				}
			}
			if structured {
				w.code("yaml", yamlText(v))
			} else {
				fmt.Fprintf(&w.buf, `<code>%s</code>`, html.EscapeString(compact(v)))
			}
		case map[string]interface{}:
			w.code("yaml", yamlText(v))
		default:
			fmt.Fprintf(&w.buf, `<code>%s</code>`, html.EscapeString(compact(value)))
		}
		w.buf.WriteString(`</dd></div>`)
	}
	w.buf.WriteString(`</dl>`)
}

type sourceProgram struct {
	path, content string
}

func writeHTMLSource(w *writer, step Step) {
	var programs []sourceProgram
	settings := sourceSettings(step.Input, "input", &programs)
	w.code("yaml", yamlText(settings))
	language := map[string]string{"go-templating": "gotemplate", "kcl": "kcl", "cue": "cue", "python": "python"}[step.Adapter]
	if language == "" {
		language = "text"
	}
	for _, program := range programs {
		w.heading(5, program.path)
		fmt.Fprintf(&w.buf, `<div class="code-block"><div class="code-bar"><span>%s</span>%s</div><pre><code class="source-code language-%s">%s</code></pre><span class="copy-status" role="status"></span></div>`, language, htmlCopyButton, language, escapedCode(program.content))
	}
}

// HTML normalizes raw CRLF before tokenization. Character references preserve
// carriage returns in the code text and clipboard without decoding literal escapes.
func escapedCode(source string) string {
	return strings.ReplaceAll(html.EscapeString(source), "\r", "&#13;")
}

// sourceSettings copies the input. Program extraction must never mutate the shared model.
func sourceSettings(value interface{}, path string, programs *[]sourceProgram) interface{} {
	switch v := value.(type) {
	case string:
		if strings.ContainsAny(v, "\r\n") {
			*programs = append(*programs, sourceProgram{path: path, content: v})
			return "See " + path + " below"
		}
		return v
	case map[string]interface{}:
		out := Object{}
		keys := make([]string, 0, len(v))
		for key := range v {
			keys = append(keys, key)
		}
		sort.Strings(keys)
		for _, key := range keys {
			out[key] = sourceSettings(v[key], path+"."+key, programs)
		}
		return out
	case []interface{}:
		out := make([]interface{}, len(v))
		for i, item := range v {
			out[i] = sourceSettings(item, fmt.Sprintf("%s[%d]", path, i), programs)
		}
		return out
	default:
		return v
	}
}
